# This program finds the average of three scores.

round1 = int(input("Enter score for round 1: ")) # Ask the user for the first score.
round2 = int(input("Enter score for round 2: ")) # Ask the user for the second score.
round3 = int(input("Enter score for round 3: ")) # Ask the user for the third score.
average = (round1 + round2 + round3) / 3 # Add the three scores and divide by 3.
print ("the average score is: ", average) # Show the average score.
